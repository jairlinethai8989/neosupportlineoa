-- 1. Create Profiles Table (for Staff)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  full_name TEXT,
  avatar_url TEXT,
  department TEXT,
  role TEXT DEFAULT 'Agent', -- 'Admin' or 'Agent'
  status TEXT DEFAULT 'Active', -- 'Active', 'Away', 'Offline'
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Create Company Settings Table
-- (Add a row and use upsert, or a single row for simple apps)
CREATE TABLE IF NOT EXISTS public.company_settings (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  company_name TEXT DEFAULT 'NEO SUPPORT',
  logo_url TEXT,
  departments TEXT[] DEFAULT ARRAY['ฝ่ายสนับสนุนลูกค้า (Customer Support)', 'ฝ่ายเทคนิค (Technical Support)', 'ฝ่ายขายและการเงิน (Sales & Billing)', 'ฝ่ายบริหาร (Management)'],
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Insert a default company row if it doesn't exist
INSERT INTO public.company_settings (company_name)
SELECT 'NEO SUPPORT'
WHERE NOT EXISTS (SELECT 1 FROM public.company_settings);

-- 3. Row Level Security (RLS)
-- Note: Simplified for dev. For production, restrict based on your requirements.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.company_settings ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public profiles are viewable by everyone." ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Users can update own profile." ON public.profiles FOR UPDATE USING (auth.uid() = id);

CREATE POLICY "Public company settings viewable by everyone." ON public.company_settings FOR SELECT USING (true);
