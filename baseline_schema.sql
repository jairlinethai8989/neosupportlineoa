-- =============================================================
-- NeoSupport Baseline Schema
-- =============================================================
-- Purpose:
--   Canonical starting schema assembled from:
--   - repository SQL migrations
--   - runtime application usage under src/
--   - SCHEMA_AUDIT.md
--
-- Important:
--   This is a baseline reconstruction, not a guaranteed byte-for-byte
--   export of the live production database.
--
-- Design goals:
--   - idempotent where practical
--   - match current app expectations
--   - preserve legacy compatibility fields when the app still references them
--   - document assumptions inline for future cleanup migrations
